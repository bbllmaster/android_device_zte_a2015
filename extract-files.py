#!/usr/bin/env python3
#
# Extract the A2015 proprietary files listed in proprietary-files.txt from a
# stock ROM update.zip (or an extracted system/ tree) into a vendor repo.
#
# Usage:
#   ./extract-files.py --rom /path/to/update.zip --vendor ../android_vendor_zte_a2015
#   ./extract-files.py --system /path/to/extracted --vendor ../android_vendor_zte_a2015
#
# The generated a2015-vendor.mk is a starting point; firmware destinations
# may need adjustment during bring-up.
#
import argparse
import os
import shutil
import sys
import zipfile

HERE = os.path.dirname(os.path.abspath(__file__))
DEFAULT_LIST = os.path.join(HERE, "proprietary-files.txt")


def read_list(path):
    entries = []
    with open(path, "r", encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if not line or line.startswith("#"):
                continue
            optional = line.startswith("-")
            entries.append((line.lstrip("-").strip(), optional))
    return entries


def dest_path(src):
    if src.startswith("system/vendor/"):
        return "$(TARGET_COPY_OUT_VENDOR)/" + src[len("system/vendor/"):]
    # Kernel firmware loader looks in /vendor/firmware, not /vendor/etc/firmware.
    if src.startswith("system/etc/firmware/"):
        return "$(TARGET_COPY_OUT_VENDOR)/firmware/" + src[len("system/etc/firmware/"):]
    if src.startswith("system/"):
        return "$(TARGET_COPY_OUT_VENDOR)/" + src[len("system/"):]
    return "$(TARGET_COPY_OUT_VENDOR)/" + src


def main():
    ap = argparse.ArgumentParser()
    group = ap.add_mutually_exclusive_group(required=True)
    group.add_argument("--rom", help="update.zip containing system/... paths")
    group.add_argument("--system", help="directory containing system/... paths")
    ap.add_argument("--vendor", required=True, help="vendor repo path")
    ap.add_argument("--list", default=DEFAULT_LIST, help="proprietary-files.txt")
    args = ap.parse_args()

    entries = read_list(args.list)
    prop_root = os.path.join(args.vendor, "proprietary")
    os.makedirs(prop_root, exist_ok=True)

    zf = zipfile.ZipFile(args.rom) if args.rom else None
    copied, missing = [], []

    for src, optional in entries:
        data = None
        if zf is not None:
            try:
                data = zf.read(src)
            except KeyError:
                data = None
        else:
            path = os.path.join(args.system, src)
            if os.path.isfile(path):
                with open(path, "rb") as f:
                    data = f.read()

        if data is None:
            if optional:
                continue
            missing.append(src)
            continue

        dst = os.path.join(prop_root, src)
        os.makedirs(os.path.dirname(dst), exist_ok=True)
        with open(dst, "wb") as f:
            f.write(data)
        copied.append(src)

    mk = os.path.join(args.vendor, "a2015-vendor.mk")
    with open(mk, "w", encoding="utf-8") as f:
        f.write("# Auto-generated by extract-files.py\n")
        f.write("PRODUCT_SOONG_NAMESPACES += vendor/zte/a2015\n\n")
        f.write("PRODUCT_COPY_FILES += \\\n")
        for i, src in enumerate(copied):
            sep = " \\" if i + 1 < len(copied) else ""
            f.write("    vendor/zte/a2015/proprietary/%s:%s%s\n" % (src, dest_path(src), sep))

    print("copied:   %d" % len(copied))
    print("missing:  %d" % len(missing))
    for src in missing:
        print("  MISSING %s" % src)
    print("generated %s" % mk)

    return 1 if missing else 0


if __name__ == "__main__":
    sys.exit(main())
